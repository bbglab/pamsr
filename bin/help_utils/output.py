import pandas as pd
import os 

def generate_sample_name(
        group_id: str,
        estimator_iteration: int,
        sample_iteration: int
    ):
    """
    Generate synthetic sample identifiers.

    Format:

        GROUP_XXXXXXX_XXXXXXX

    where:

    - First number identifies the estimator draw.
    - Second number identifies the sample drawn from that estimator.

    Parameters
    ----------
    group_id : str
        Mutation group identifier.

    estimator_iteration : int
        Index of the Dirichlet/NB parameter draw.

    sample_iteration : int
        Index of the multinomial sample draw.

    Returns
    -------
    str
        Synthetic sample identifier.

    Examples
    --------
    >>> generate_sample_name("A",1,3)

    'A_0000001_0000003'
    """

    return (
        f"{group_id}_"
        f"{estimator_iteration:07d}_"
        f"{sample_iteration:07d}"
    )

def save_synthetic_matrix(
        synthetic_matrix: pd.DataFrame,
        synthetic_names: list,
        path_folder: str,
        name: str
    ):
    """
    Save a synthetic mutational matrix in SBS96 format.

    Parameters
    ----------
    synthetic_matrix : pandas.DataFrame
        Synthetic mutation count matrix.

    synthetic_names : list
        List of synthetic sample identifiers generated by
        generate_sample_name().

        Example:

            [
                "A_0000001_0000001",
                "A_0000001_0000002",
                "A_0000001_0000003"
            ]

    path : str
        Output CSV path.

    Returns
    -------
    None
        Writes the dataframe to disk.
    """

    mutation_types = (
            'A[C>A]A', 'A[C>A]C', 'A[C>A]G', 'A[C>A]T',
            'A[C>G]A', 'A[C>G]C', 'A[C>G]G', 'A[C>G]T',
            'A[C>T]A', 'A[C>T]C', 'A[C>T]G', 'A[C>T]T',
            'A[T>A]A', 'A[T>A]C', 'A[T>A]G', 'A[T>A]T',
            'A[T>C]A', 'A[T>C]C', 'A[T>C]G', 'A[T>C]T',
            'A[T>G]A', 'A[T>G]C', 'A[T>G]G', 'A[T>G]T',
            'C[C>A]A', 'C[C>A]C', 'C[C>A]G', 'C[C>A]T',
            'C[C>G]A', 'C[C>G]C', 'C[C>G]G', 'C[C>G]T',
            'C[C>T]A', 'C[C>T]C', 'C[C>T]G', 'C[C>T]T',
            'C[T>A]A', 'C[T>A]C', 'C[T>A]G', 'C[T>A]T',
            'C[T>C]A', 'C[T>C]C', 'C[T>C]G', 'C[T>C]T',
            'C[T>G]A', 'C[T>G]C', 'C[T>G]G', 'C[T>G]T',
            'G[C>A]A', 'G[C>A]C', 'G[C>A]G', 'G[C>A]T',
            'G[C>G]A', 'G[C>G]C', 'G[C>G]G', 'G[C>G]T',
            'G[C>T]A', 'G[C>T]C', 'G[C>T]G', 'G[C>T]T',
            'G[T>A]A', 'G[T>A]C', 'G[T>A]G', 'G[T>A]T',
            'G[T>C]A', 'G[T>C]C', 'G[T>C]G', 'G[T>C]T',
            'G[T>G]A', 'G[T>G]C', 'G[T>G]G', 'G[T>G]T',
            'T[C>A]A', 'T[C>A]C', 'T[C>A]G', 'T[C>A]T',
            'T[C>G]A', 'T[C>G]C', 'T[C>G]G', 'T[C>G]T',
            'T[C>T]A', 'T[C>T]C', 'T[C>T]G', 'T[C>T]T',
            'T[T>A]A', 'T[T>A]C', 'T[T>A]G', 'T[T>A]T',
            'T[T>C]A', 'T[T>C]C', 'T[T>C]G', 'T[T>C]T',
            'T[T>G]A', 'T[T>G]C', 'T[T>G]G', 'T[T>G]T'
        )
    
    if "Mutation Types" not in synthetic_matrix.columns:
        raise ValueError(
            "Synthetic matrix must contain a 'Mutation Types' column"
        )

    matrix = synthetic_matrix.copy()

    if len(synthetic_names) != len(matrix.columns) - 1:
        raise ValueError(
            "Number of synthetic names must match "
            "number of synthetic samples."
        )

    matrix.columns = (
        ["Mutation Types"]
        +
        synthetic_names
    )

    matrix["Mutation Types"] = mutation_types

    os.makedirs(path_folder, exist_ok=True)

    output_file = os.path.join(
            path_folder,
            f"{name}.csv"
        )
    
    if os.path.exists(output_file):
        raise FileExistsError(
            f"The file already exists: {output_file}"
        )

    matrix.to_csv(
        output_file,
        index=False
    )